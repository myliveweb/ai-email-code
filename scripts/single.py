"""Один прогон на скрипт: второй такой же не должен запускаться.

Крон-прогоны стали дольше своего шага: 25.08 `gorouter_balance.py` стартовал в 06:37
и закончил в 07:00 (шесть аккаунтов tabitoken отвалились по сети, каждый со своими
повторами и таймаутами), то есть в 06:52 крон поднял второй экземпляр поверх живого.
Два экземпляра пишут одни и те же строки в базу и один и тот же файл отчёта, и тот,
кто финиширует позже, затирает свежие цифры своими — более старыми, потому что он
собирал их раньше.

Механика — `flock` на отдельном файле в `log/`. Не pid-файл: pid надо проверять на
живость и вычищать за упавшим процессом, а блокировка снимается ядром сама, чем бы
прогон ни кончился — исключением, `kill -9` или перезагрузкой. Файл только держит
блокировку, содержимое (pid и время старта) пишется для человека, который смотрит,
кто сидит.

Разные скрипты друг друга не задевают: имя файла своё у каждого.
"""

import fcntl
import os
from datetime import datetime
from pathlib import Path
from typing import IO

LOCK_DIR = Path(__file__).resolve().parent.parent / "log"


def hold_lock(name: str) -> IO[str] | None:
    """Занять блокировку прогона. None — уже работает такой же, надо выйти.

    Возвращённый файл нужно держать в переменной до конца прогона: закрытие файла
    снимает блокировку, а сборщик мусора закроет его сразу, если ссылку не хранить.
    """
    LOCK_DIR.mkdir(exist_ok=True)
    handle = (LOCK_DIR / f"{name}.lock").open("a+", encoding="utf-8")
    try:
        fcntl.flock(handle, fcntl.LOCK_EX | fcntl.LOCK_NB)
    except OSError:
        handle.seek(0)
        who = handle.read().strip() or "неизвестно кто"
        handle.close()
        print(f"прогон {name} уже идёт ({who}) — второй экземпляр не нужен, выхожу")
        return None
    handle.seek(0)
    handle.truncate()
    handle.write(f"pid {os.getpid()}, старт {datetime.now().astimezone():%Y-%m-%d %H:%M:%S}\n")
    handle.flush()
    return handle
